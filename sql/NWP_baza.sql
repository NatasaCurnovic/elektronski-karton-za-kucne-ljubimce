CREATE DATABASE IF NOT EXISTS elektronski_karton_ljubimci CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE elektronski_karton_ljubimci;

CREATE TABLE users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 first_name VARCHAR(100) NOT NULL, last_name VARCHAR(100) NOT NULL,
 email VARCHAR(191) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 phone VARCHAR(30), role ENUM('OWNER','VETERINARIAN','ADMIN') NOT NULL DEFAULT 'OWNER',
 is_active BOOLEAN NOT NULL DEFAULT TRUE, is_email_verified BOOLEAN NOT NULL DEFAULT FALSE,
 activation_token VARCHAR(255) UNIQUE, activation_expires_at DATETIME,
 reset_token VARCHAR(255) UNIQUE, reset_expires_at DATETIME,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE veterinary_stations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(150) NOT NULL, address VARCHAR(255) NOT NULL, city VARCHAR(100) NOT NULL,
 phone VARCHAR(30) NOT NULL, email VARCHAR(191), created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE veterinarian_profiles (
 user_id BIGINT UNSIGNED PRIMARY KEY, veterinary_station_id BIGINT UNSIGNED NOT NULL,
 license_number VARCHAR(100) UNIQUE, specialization VARCHAR(150),
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (veterinary_station_id) REFERENCES veterinary_stations(id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE pets (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 owner_id BIGINT UNSIGNED NOT NULL, veterinarian_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(100) NOT NULL, species VARCHAR(100) NOT NULL, breed VARCHAR(100),
 sex ENUM('MALE','FEMALE','UNKNOWN') NOT NULL DEFAULT 'UNKNOWN', date_of_birth DATE,
 microchip_number VARCHAR(100) UNIQUE, profile_photo VARCHAR(255), is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY (veterinarian_id) REFERENCES users(id) ON DELETE RESTRICT,
 INDEX(owner_id), INDEX(veterinarian_id)
) ENGINE=InnoDB;

CREATE TABLE pet_qr_codes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, pet_id BIGINT UNSIGNED NOT NULL UNIQUE,
 public_token CHAR(64) NOT NULL UNIQUE, is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (pet_id) REFERENCES pets(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE examinations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, pet_id BIGINT UNSIGNED NOT NULL,
 veterinarian_id BIGINT UNSIGNED NOT NULL, examination_date DATETIME NOT NULL,
 description TEXT NOT NULL, findings TEXT, notes TEXT,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (pet_id) REFERENCES pets(id) ON DELETE RESTRICT,
 FOREIGN KEY (veterinarian_id) REFERENCES users(id) ON DELETE RESTRICT,
 INDEX(pet_id, examination_date), INDEX(veterinarian_id, examination_date)
) ENGINE=InnoDB;

CREATE TABLE treatments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, pet_id BIGINT UNSIGNED NOT NULL,
 veterinarian_id BIGINT UNSIGNED NOT NULL, examination_id BIGINT UNSIGNED,
 treatment_date DATE NOT NULL, title VARCHAR(150) NOT NULL, description TEXT NOT NULL, notes TEXT,
 FOREIGN KEY (pet_id) REFERENCES pets(id) ON DELETE RESTRICT,
 FOREIGN KEY (veterinarian_id) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY (examination_id) REFERENCES examinations(id) ON DELETE SET NULL,
 INDEX(pet_id, treatment_date)
) ENGINE=InnoDB;

CREATE TABLE appointment_slots (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, veterinarian_id BIGINT UNSIGNED NOT NULL,
 start_time DATETIME NOT NULL, end_time DATETIME NOT NULL,
 status ENUM('AVAILABLE','BOOKED','CANCELLED') NOT NULL DEFAULT 'AVAILABLE',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (veterinarian_id) REFERENCES users(id) ON DELETE CASCADE,
 CHECK (end_time > start_time), INDEX(veterinarian_id, start_time)
) ENGINE=InnoDB;

CREATE TABLE appointments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, slot_id BIGINT UNSIGNED NOT NULL UNIQUE,
 pet_id BIGINT UNSIGNED NOT NULL, owner_id BIGINT UNSIGNED NOT NULL, veterinarian_id BIGINT UNSIGNED NOT NULL,
 status ENUM('SCHEDULED','COMPLETED','CANCELLED_BY_OWNER','CANCELLED_BY_VETERINARIAN') NOT NULL DEFAULT 'SCHEDULED',
 cancellation_reason TEXT, cancelled_at DATETIME,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (slot_id) REFERENCES appointment_slots(id) ON DELETE RESTRICT,
 FOREIGN KEY (pet_id) REFERENCES pets(id) ON DELETE RESTRICT,
 FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY (veterinarian_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE notification_preferences (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL UNIQUE,
 appointment_reminders BOOLEAN NOT NULL DEFAULT TRUE, treatment_reminders BOOLEAN NOT NULL DEFAULT TRUE,
 cancellation_notifications BOOLEAN NOT NULL DEFAULT TRUE,
 appointment_reminder_hours SMALLINT UNSIGNED NOT NULL DEFAULT 24,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- DODATNA FUNKCIONALNOST 1: zdravstveni dnevnik
CREATE TABLE health_diary_entries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, pet_id BIGINT UNSIGNED NOT NULL,
 owner_id BIGINT UNSIGNED NOT NULL, entry_date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 weight_kg DECIMAL(5,2), appetite ENUM('VERY_LOW','LOW','NORMAL','HIGH','VERY_HIGH'),
 activity_level ENUM('VERY_LOW','LOW','NORMAL','HIGH','VERY_HIGH'),
 symptoms TEXT, behavior_notes TEXT, notes TEXT,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (pet_id) REFERENCES pets(id) ON DELETE CASCADE,
 FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE RESTRICT,
 CHECK (weight_kg IS NULL OR weight_kg > 0), INDEX(pet_id, entry_date)
) ENGINE=InnoDB;

-- DODATNA FUNKCIONALNOST 2: lista čekanja
CREATE TABLE appointment_waitlist (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, pet_id BIGINT UNSIGNED NOT NULL,
 owner_id BIGINT UNSIGNED NOT NULL, veterinarian_id BIGINT UNSIGNED NOT NULL,
 preferred_from DATETIME NOT NULL, preferred_until DATETIME NOT NULL,
 status ENUM('WAITING','OFFERED','ACCEPTED','EXPIRED','CANCELLED') NOT NULL DEFAULT 'WAITING',
 offered_slot_id BIGINT UNSIGNED, offer_expires_at DATETIME,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (pet_id) REFERENCES pets(id) ON DELETE CASCADE,
 FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (veterinarian_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (offered_slot_id) REFERENCES appointment_slots(id) ON DELETE SET NULL,
 CHECK (preferred_until > preferred_from), INDEX(veterinarian_id, status)
) ENGINE=InnoDB;

-- DODATNA FUNKCIONALNOST 3: istorija generisanih zdravstvenih izveštaja
CREATE TABLE health_reports (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, pet_id BIGINT UNSIGNED NOT NULL,
 generated_by_user_id BIGINT UNSIGNED NOT NULL,
 report_title VARCHAR(200) NOT NULL DEFAULT 'Zdravstveni izveštaj ljubimca',
 period_from DATE, period_until DATE, file_path VARCHAR(255),
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (pet_id) REFERENCES pets(id) ON DELETE RESTRICT,
 FOREIGN KEY (generated_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
 INDEX(pet_id)
) ENGINE=InnoDB;

CREATE TABLE notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 appointment_id BIGINT UNSIGNED,
 type ENUM('ACCOUNT_ACTIVATION','PASSWORD_RESET','APPOINTMENT_REMINDER','TREATMENT_REMINDER','APPOINTMENT_CANCELLED','WAITLIST_OFFER') NOT NULL,
 subject VARCHAR(255) NOT NULL, status ENUM('PENDING','SENT','FAILED') NOT NULL DEFAULT 'PENDING',
 sent_at DATETIME, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (appointment_id) REFERENCES appointments(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE VIEW vw_veterinarian_statistics AS
SELECT u.id AS veterinarian_id, CONCAT(u.first_name,' ',u.last_name) AS veterinarian_name,
 COUNT(DISTINCT p.id) AS assigned_pets, COUNT(DISTINCT e.id) AS completed_examinations
FROM users u
LEFT JOIN pets p ON p.veterinarian_id=u.id
LEFT JOIN examinations e ON e.veterinarian_id=u.id
WHERE u.role='VETERINARIAN'
GROUP BY u.id,u.first_name,u.last_name;
